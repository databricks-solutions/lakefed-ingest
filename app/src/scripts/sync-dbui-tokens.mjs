// Copy the Databricks design system's (dbui, @databricks/design-system) published CSS tokens and its
// DM Sans font into frontend/src/dbui/, so the app looks like the workspace without installing the
// component library (antd and Emotion, several hundred packages, on every deploy).
//
// Usage: node scripts/sync-dbui-tokens.mjs <path to an installed @databricks/design-system>
// The token blocks are copied unchanged (names, values and aliases), from the package's public
// index.css: every rule whose selector targets :root (the light theme).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = process.argv[2];
if (!pkg) {
  console.error("usage: node scripts/sync-dbui-tokens.mjs <path to @databricks/design-system>");
  process.exit(2);
}
const meta = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
const css = readFileSync(join(pkg, "dist", "index.css"), "utf8");
const out = join(import.meta.dirname, "..", "frontend", "src", "dbui");
mkdirSync(out, { recursive: true });

const blocks = [];
for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const selector = match[1].replace(/\/\*[\s\S]*?\*\//g, "").trim();
  if (selector.includes(":root") && match[2].includes("--db-")) blocks.push(`${selector} {${match[2]}}`);
}
const header = `/* Generated by scripts/sync-dbui-tokens.mjs from ${meta.name} ${meta.version} (${meta.license}),
   dist/index.css: its light-theme CSS tokens, unchanged. Do not edit; re-run the script to update. */\n`;
writeFileSync(join(out, "tokens.css"), header + blocks.join("\n") + "\n");
copyFileSync(join(pkg, "dist", "fonts", "dm-sans", "DMSans-variable.woff2"), join(out, "DMSans-variable.woff2"));
writeFileSync(join(out, "dm-sans.css"), readFileSync(join(pkg, "dist", "fonts", "dm-sans", "dm-sans.css"), "utf8"));
console.log(`${blocks.length} token blocks from ${meta.name} ${meta.version} into ${out}`);
